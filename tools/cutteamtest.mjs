// 커트라인 — 한 문장에 답이 두 개면 서로 검산한다.
//
//  실측 2026-08-23 #27554: "3부 16팀, 오동현(조하빈)님까지 근무됩니다."
//   괄호 점유자 규칙만 쓰면 조하빈(명단 10번)이 컷이 되어 '16팀'과 6칸 어긋났다.
//   그 바람에 티오프를 들고 있던 11~15번이 통째로 스페어로 꺼졌다 —
//   박준서 17:14 · 최재영 17:21 · 박수현 17:28. 출발 시각을 40분 앞두고.
//  ★괄호 규칙 자체는 옳다("송민지님(박준서)까지" = 그 자리 주인은 박준서).
//   팀 수가 같이 왔을 때만, 그리고 괄호가 어긋나고 앞 이름이 딱 맞을 때만 앞 이름을 쓴다.
import { resolveCutoff } from '../src/judge.mjs';

let pass = 0, fail = 0;
const ok = (c, what, why = '') => {
  if (c) { pass++; console.log('  OK ' + what); }
  else { fail++; console.log('  X  ' + what + (why ? '  — ' + why : '')); }
};
// 8/23 실제 3부 명단(앞 18)
const ROSTER = ['박진수(54)', '박선하', '이하늘(54)', '김서현', '김민찬', '문태익(54)', '우겸조', '정용호',
  '김동우(54)', '조하빈(54)', '강혜영', '박준서', '류곤', '최재영(2,3)', '박수현(2,3)', '오동현(2,3)',
  '윤형수(2,3)', '장성원(2,3)'];
const cut = (subject) => {
  const v = { part3Roster: ROSTER.slice() };
  resolveCutoff(v, { subject, text: '' }, null);
  return { pos: v.cutoffPosition || 0, name: v.cutoffName || '', src: v._cutSource || '', bad: v._cutMismatch || null };
};

console.log('\n[★그날 그 문장]');
{
  const r = cut('3부 16팀, 오동현(조하빈)님까지 근무됩니다.');
  ok(r.pos === 16, `커트 16번 (나온 값 ${r.pos})`, '조하빈=10번을 쓰면 11~15번이 통째로 스페어가 된다');
  ok(r.name === '오동현', `커트 이름 오동현 (나온 값 ${r.name})`);
  ok(/팀수검산/.test(r.src), '왜 그렇게 골랐는지 남긴다', '조용히 고르면 다음에 왜 틀렸는지 알 수 없다');
}

console.log('\n[괄호 규칙은 그대로 산다 — 팀 수가 없을 때]');
{
  const r = cut('송민지(박준서)님까지 근무됩니다.');
  ok(r.pos === 12 && r.name === '박준서', `괄호 안 사람이 컷 (${r.name} ${r.pos}번)`,
    '괄호 안 이름이 그 자리의 실제 주인이라는 원칙은 유지된다');
  const r2 = cut('장성원님까지 근무됩니다.');
  ok(r2.pos === 18 && r2.name === '장성원', `괄호가 없으면 그 이름 (${r2.name} ${r2.pos}번)`);
}

console.log('\n[팀 수가 괄호 쪽과 맞으면 괄호가 이긴다]');
{
  const r = cut('3부 10팀, 오동현(조하빈)님까지 근무됩니다.');
  ok(r.pos === 10 && r.name === '조하빈', `10팀이면 조하빈(10번) (${r.name} ${r.pos}번)`,
    '검산은 팀 수 편이지 특정 이름 편이 아니다');
}

console.log('\n[어느 쪽도 안 맞으면 조용히 넘어가지 않는다]');
{
  const r = cut('3부 25팀, 오동현(조하빈)님까지 근무됩니다.');
  ok(!!r.bad, '어긋남을 판정에 남긴다');
  ok(r.bad && r.bad.teams === 25 && r.bad.holderPos === 10,
    `무엇이 어긋났는지 적는다 (${r.bad?.teams}팀 vs ${r.bad?.holderPos}번)`,
    '사람이 검수에서 볼 수 있어야 한다');
  ok(r.pos === 10, '그래도 판정 자체는 종전대로 둔다', '모를 때 멋대로 바꾸면 그게 더 위험하다');
}

console.log('\n[숫자를 잘못 집지 않는가]');
{
  const r = cut('3부 16팀, 오동현(조하빈)님까지 근무됩니다.');
  ok(r.pos === 16, "'3부'의 3을 팀 수로 읽지 않는다");
  const r2 = cut('장성원님까지 근무됩니다.');
  ok(r2.pos === 18, '팀 수가 없으면 검산을 시도하지 않는다');
}

console.log(`\n${fail ? 'X' : 'OK'}  통과 ${pass} · 실패 ${fail}\n`);
process.exit(fail ? 1 : 0);
